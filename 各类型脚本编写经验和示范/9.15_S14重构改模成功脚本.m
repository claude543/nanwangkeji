critical={SM,SS2,strategy,strategyCore,stack,gate,gateCore,island,globalStage, ...
    coord,coordCore,qbias,qrouter,ess2Mux,prefFrom,stageFrom,restoreStageFrom, ...
    restoreStatusGoto,g29Mux,g29,exec,execCore,cfg,adapterCore};
for k=1:numel(critical),mustBlock(critical{k});end

if ~strcmp(get_param(mdl,'Dirty'),'off')
    error('S14V2R1:PreDirty','preflight要求模型Dirty=off。');
end

if ~strcmpi(hashText(emChartScript(strategyCore)),strategySha)
    error('S14V2R1:StrategyDrift','Advanced Strategy源码已漂移，停止覆盖。');
end
if ~strcmpi(hashText(emChartScript(gateCore)),gateSha)
    error('S14V2R1:GateDrift','Black Start Pref Gate源码已漂移，停止覆盖。');
end
if ~strcmpi(hashText(emChartScript(coordCore)),coordSha)
    error('S14V2R1:CoordDrift','Island Coordinator源码已漂移，停止覆盖。');
end
if ~strcmpi(hashText(emChartScript(execCore)),execSha)
    error('S14V2R1:ExecDrift','ESS2 Restore Executor源码已漂移，停止覆盖。');
end
if ~strcmpi(hashText(emChartScript(adapterCore)),adapterSha)
    error('S14V2R1:AdapterDrift','Current Adapter源码已漂移；本轮冻结区被改动。');
end

% External contracts before patch.
ph=get_param(strategy,'PortHandles');
if numel(ph.Inport)~=40 || numel(ph.Outport)~=4
    error('S14V2R1:StrategyOuter','15策略外层不是40入4出。');
end
ph=get_param(strategyCore,'PortHandles');
if numel(ph.Inport)~=40 || numel(ph.Outport)~=4
    error('S14V2R1:StrategyCorePre','Strategy Core pre不是40入4出。');
end
ph=get_param(gateCore,'PortHandles');
if numel(ph.Inport)~=14 || numel(ph.Outport)~=11
    error('S14V2R1:GatePorts','Black Start Pref Gate Core不是14入11出。');
end
ph=get_param(coord,'PortHandles');
if numel(ph.Inport)~=30 || numel(ph.Outport)~=31
    error('S14V2R1:CoordOuter','Coordinator外层不是30入31出。');
end
ph=get_param(coordCore,'PortHandles');
if numel(ph.Inport)~=59 || numel(ph.Outport)~=48
    error('S14V2R1:CoordCorePre','Coordinator Core pre不是59入48出。');
end

% Current exact direct-route contracts.
assertDirectConnection(prefFrom,1,ess2Mux,6);
assertDirectConnection(stageFrom,1,ess2Mux,5);
assertDirectConnection(globalStage,1,coord,1);
assertDirectConnection(globalStage,1,qbias,1);
assertDirectConnection(globalStage,1,qrouter,1);
if ~strcmp(safeGet(restoreStageFrom,'GotoTag'),'AA15_BS_STAGE_ECHO')
    error('S14V2R1:RestoreStagePre','Restore Stage From当前tag不是AA15_BS_STAGE_ECHO。');
end
if ~strcmp(safeGet(restoreStatusGoto,'GotoTag'),'AA15_ESS2_RESTORE_STATUS_VEC')
    error('S14V2R1:RestoreStatusPre','现有ESS2恢复状态返回tag漂移。');
end

% Restore config current 31 contract.
mux=find_system(cfg,'SearchDepth',1,'BlockType','Mux');
if numel(mux)~=1 || parseMuxInputCount(get_param(mux{1},'Inputs'))~=31
    error('S14V2R1:Cfg31','Restore Config pre不是31维。');
end
mustBlock([cfg '/CFG_ESS2_RESTORE_STAGE_TRIGGER_MIN']);
if abs(resolveScalar(mdl,safeGet([cfg '/CFG_ESS2_RESTORE_STAGE_TRIGGER_MIN'],'Value'))-2)>1e-12
    error('S14V2R1:StageTriggerPre','Restore Stage Trigger pre不是2。');
end

% G29 current 46 scalar inputs and exact OpWrite family.
if parseMuxInputCount(get_param(g29Mux,'Inputs'))~=46
    error('S14V2R1:G29PreWidth','G29 pre不是46通道。');
end
if ~contains(lower(referenceFamily(g29)),'opwritefile')
    error('S14V2R1:G29Family','G29不是OpWriteFile family。');
end
if readNumericMaskProven(g29,'Acq_Group')~=29 || readNumericMaskProven(g29,'Decimation')~=4
    error('S14V2R1:G29Mask','G29 group/decimation漂移。');
end

ops=findAllOpWritesProven(mdl);
groups=sort(cellfun(@(b)readNumericMaskProven(b,'Acq_Group'),ops));
if numel(ops)~=5 || ~isequal(groups,26:30)
    error('S14V2R1:OpWritePre','当前OpWrite必须仍只有G26~G30，实际=%s。',mat2str(groups));
end

% Frozen cross-task dimensions.
if ~strcmp(strtrim(get_param([SM '/ESS_IO_Memory24'],'InitialCondition')),'zeros(25,1)')
    error('S14V2R1:SM25','SM->SS2不是25维。');
end
if ~strcmp(strtrim(get_param([SS2 '/Memory'],'InitialCondition')),'zeros(45,1)')
    error('S14V2R1:Return45','SS2->SM不是45维。');
end

% New R1 blocks must not already exist: do not half-reapply.
newNames={ ...
    [SM '/AA15_S14V2_CFG_PICKUP_TARGET_PU'], ...
    [SM '/AA15_S14V2_CFG_ESS2_COORD_AUTH_PU'], ...
    [SM '/AA15_S14V2_ESS2_P_OWNERSHIP_BLEND'], ...
    [SM '/AA15_S14V2_ESS2_GFL_STAGE_SWITCH'], ...
    [island '/AA15_S14V2_COORD_STAGE_SWITCH'], ...
    [island '/AA15_S14V2_CORRECTION_GAIN_RATE_LIMITER'] ...
};
for k=1:numel(newNames)
    if getSimulinkBlockHandle(newNames{k})>=0
        error('S14V2R1:AlreadyPatched','检测到R1新块已存在：%s',newNames{k});
    end
end

% New global tags must also be absent; duplicate Goto tags are not auto-resolved.
newTags=[s14ExecTags(), { ...
    'AA15_S14V2_HANDOVER_BETA', ...
    'AA15_S14V2_ESS2_GFL_STAGE_EFFECTIVE', ...
    'AA15_S14V2_CORRECTION_GAIN_ACTUAL', ...
    'AA15_S14V2_ESS2_COORD_AUTH_PU'}];
for k=1:numel(newTags)
    hits=find_system(mdl,'LookUnderMasks','all','FollowLinks','on', ...
        'BlockType','Goto','GotoTag',newTags{k});
    if ~isempty(hits)
        error('S14V2R1:TagExists','新全局tag已存在：%s，GotoCount=%d',newTags{k},numel(hits));
    end
end

B=struct();
B.strategyCoreFirst40=captureInputEndpoints(strategyCore,40);
B.gateCoreFirst14=captureInputEndpoints(gateCore,14);
B.coordCoreFirst59=captureInputEndpoints(coordCore,59);
B.execCoreFirst6=captureInputEndpoints(execCore,6);
B.g29First46=captureInputEndpoints(g29Mux,46);
B.rawSha256=sha256File(get_param(mdl,'FileName'));
end

