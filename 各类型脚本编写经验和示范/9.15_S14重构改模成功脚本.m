function pos=findFreePosition(parent,desiredCenter,wh,margin)
blocks=find_system(parent,'SearchDepth',1,'Type','Block');
rects=zeros(0,4);
for k=1:numel(blocks)
    if strcmp(blocks{k},parent),continue;end
    try r=double(get_param(blocks{k},'Position'));if numel(r)==4,rects(end+1,:)=r;end %#ok<AGROW>
    catch,end
end
pos=findFreePositionFromRects(rects,desiredCenter,wh,margin);
end

function pos=findFreePositionFromRects(rects,desiredCenter,wh,margin)
w=wh(1);h=wh(2);
offsets=[0 0;220 0;-220 0;0 180;0 -180;440 0;-440 0;220 180;220 -180;-220 180;-220 -180;0 360;0 -360];
for k=1:size(offsets,1)
    c=desiredCenter+offsets(k,:);
    p=round([c(1)-w/2 c(2)-h/2 c(1)+w/2 c(2)+h/2]);
    ok=true;
    for j=1:size(rects,1)
        if rectOverlap(p,rects(j,:),margin),ok=false;break;end
    end
    if ok,pos=p;return;end
end
% deterministic rightward search
x=max([desiredCenter(1),max([0;rects(:,3)])+margin+w/2+20]);
c=[x desiredCenter(2)];
pos=round([c(1)-w/2 c(2)-h/2 c(1)+w/2 c(2)+h/2]);
end

function tf=rectOverlap(a,b,m)
tf=~(a(3)+m<=b(1)||b(3)+m<=a(1)||a(4)+m<=b(2)||b(4)+m<=a(2));
end

