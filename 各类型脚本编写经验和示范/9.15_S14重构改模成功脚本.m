% 当前模型语义preflight（只读）
% =========================================================================
function B=preflightCurrentModel(mdl,strategySha,gateSha,coordSha,execSha,adapterSha)
SM=[mdl '/SM_Master'];
SS2=[mdl '/SS_Slave2'];
strategy=[SM '/Advanced_Microgrid_15_Strategies'];
strategyCore=[strategy '/Advanced_Strategy_Core'];
stack=[SM '/AA15_LOCAL_CONTROL_STACK'];
gate=[stack '/AA15_Black_Start_Pref_Gate'];
gateCore=[gate '/AA15_Black_Start_Pref_Gate_Core'];
island=[SM '/AA15_ISLAND_SUPERVISORY_COORDINATION'];
globalStage=[island '/AA15_FINAL_SYSTEM_STAGE'];
coord=[island '/AA15_FINAL_ISLAND_COORDINATOR'];
coordCore=[coord '/AA15_FINAL_COORD_CORE'];
qbias=[island '/AA15_V48_ISLAND_QBIAS_COORDINATOR'];
qrouter=[island '/AA15_V48_QREF_QBIAS_ROUTER_ESS2'];
ess2Mux=[SM '/ESS2_IO_Mux12'];
