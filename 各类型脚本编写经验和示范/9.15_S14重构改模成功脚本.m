function connectReplacingInputAbs(parent,srcBlock,srcPort,dstBlock,dstPort)
mustBlock(srcBlock);mustBlock(dstBlock);
sph=get_param(srcBlock,'PortHandles');dph=get_param(dstBlock,'PortHandles');
if srcPort<1||srcPort>numel(sph.Outport)||dstPort<1||dstPort>numel(dph.Inport)
    error('S14V2R1:Port','无效端口：%s/%d -> %s/%d',srcBlock,srcPort,dstBlock,dstPort);
end
lh=get_param(dph.Inport(dstPort),'Line');
if ~isempty(lh)&&any(lh>=0)
    sb=get_param(lh,'SrcBlockHandle');sp=get_param(lh,'SrcPortHandle');
    if isscalar(sb)&&sb==getSimulinkBlockHandle(srcBlock)
        pn=NaN;try pn=get_param(sp,'PortNumber');catch,end
        if pn==srcPort,return;end
    end
    delete_line(lh);
end
add_line(parent,sph.Outport(srcPort),dph.Inport(dstPort),'autorouting','on');
assertDirectConnection(srcBlock,srcPort,dstBlock,dstPort);
end

