% =========================================================================
function staticSourceQA(src,label)
if isempty(strtrim(src)),error('S14V2R1:SourceEmpty','%s为空。',label);end
bad=regexp(src,'(?m)(?:&&|\|\|)\s*$','match');
if ~isempty(bad)
    error('S14V2R1:BareBoolean','%s存在未用...续行的&&/||物理行。',label);
end
if contains(src,'elif_placeholder') || contains(src,'<PLACEHOLDER>')
    error('S14V2R1:Placeholder','%s含placeholder。',label);
end
if countTokenOutsideComments(src,'function')<1
    error('S14V2R1:NoFunction','%s没有function定义。',label);
end
end

function n=countTokenOutsideComments(src,tok)
L=regexp(src,'\r\n|\n|\r','split');n=0;
for k=1:numel(L)
    s=strtrim(L{k});
    if startsWith(s,'%'),continue;end
    n=n+numel(strfind(s,tok));
end
end

