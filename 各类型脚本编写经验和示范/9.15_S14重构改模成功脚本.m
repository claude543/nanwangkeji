function result = PATCH_K26_K50_S14_V2_ESS2_PICKUP_HANDOVER_R1(modelRoot)
% PATCH_K26_K50_S14_V2_ESS2_PICKUP_HANDOVER_R1
% =========================================================================
% K26_K50_CLEAN_P1
% S14 V2（策略14黑启动V2）+ ESS2（储能2）固定小功率承担
% + normal island Coordinator（正常孤岛协调器）平滑接管 正式 Patch（改模脚本）R1
%
% 本轮一次性解决的已确认设计缺陷：
% 1) S14 旧逻辑仅按绝对时间20/40/60 s推进，不读取真实设备恢复状态；
% 2) Black Start Pref Gate（黑启动有功参考门）按粗Stage直接恢复旧Pref，
%    导致“策略阶段”被错误等同为“物理设备已经恢复”；
% 3) 正常孤岛 Coordinator 默认五台GFL全部在线，黑启动逐台恢复时
%    availability（物理可用资格）与真实状态不一致；
% 4) ESS2设备额定[-1,+1] pu能力被正常协调器直接当调节能力，未区分
%    “设备可用”与“当前允许承担多少协调修正”；
% 5) R7中固定功率尚未建立，normal Coordinator目标、RestoreAlpha和
%    Power PI同时运动，无法回答ESS2是否存在稳定非零工作点；
% 6) 一个AA15_FINAL_SYSTEM_STAGE同时承担中央Coordinator、ESS2本地GFL
%    和Restore Executor三种阶段语义，逐台黑启动无法正确排时；
% 7) ESS2 local Stage与Qref/q-bias源端router若语义不同，会把同一标量
%    在发送端当Qref、接收端当q-bias，必须同步对齐；
% 8) 旧state6只按时间把RestoreAlpha从0拉到1，state7只代表“计时结束”，
%    不代表固定非零功率真实稳定；
% 9) G29缺少S14子状态、三类Stage、所有权、beta、availability、
%    correction gain等系统级因果证据。
%
% 冻结不改：
% - ESS1 GFM（构网型）主体；
% - ESS2 state0~5已验证的物理判断/真实合闸/零功率算法，只增加阶段互锁；
% - ESS2 Current Adapter（电流执行适配器）源码/Kp/Ki/VFF/helper；
% - ESS2 Power PI（功率比例积分调节器）Kp/Ki；
% - 已成功的breaker-inner真实测量、真实breaker链、G27=62、G30=128；
% - PV1/PV2/EV1/EV2物理恢复执行器，本轮绝不复制ESS2逻辑；
% - SM->SS2 25维与SS2->SM 45维跨任务合同。
%
% R1故意不做：
% - 不自动开启Secondary（正常二次频率/电压恢复）；
% - 不虚构未经实验认证的ESS1动态余量公式；
% - 不新增G31；
% - 不写下一轮Python Runner（必须等本Patch+Verifier+RT-LAB Rebuild后，
%   按新Build真实参数/信号合同再写）。
%
% 工程事务规则（直接复用已成功V8/R3/V3.4经验）：
% - whole-SLX raw SHA只记录，不作为语义硬门；
% - 当前关键源码哈希+接口+真实连接才是preflight硬门；
% - pure QA -> production-equivalent Harness -> byte-identical scratch
%   -> formal backup -> formal edit -> postassert -> save exactly once
%   -> close/reload -> persistence postassert；
% - 正式save后若任何检查失败，whole-file backup字节级回滚；
% - Patch与独立Verifier分离；
% - 本脚本只修改普通Simulink控制/诊断结构，不碰任何SPS物理线；
% - UNKNOWN/歧义不猜，不自动取“第一个看起来像”的候选。
%
% MATLAB R2023b
% =========================================================================

VERSION='K26_K50_S14_V2_ESS2_PICKUP_HANDOVER_R1_20260915';
MODEL='K26_K50_CLEAN_P1';

% Current semantic identity from one-pass architecture audit R1.
EXPECTED_STRATEGY_PRE_SHA='7caa43572ef5c3486b122bf74abd0f184000b02ab34814a9f2694fb6cb828d5b';
EXPECTED_GATE_PRE_SHA='a36a217dd372d593548fe7ad07117edbe049ce5e28385f8f0903986740ef892e';
EXPECTED_COORD_PRE_SHA='5917226035eaae5acfeda2234adea0f973fbd1cde52879af29c8464099d2f77f';
EXPECTED_EXEC_PRE_SHA='dedb73e5d3945fddc8bd9f819182f9f840d4cc0f3617b0736285b81cc78525ec';
EXPECTED_ADAPTER_SHA='1414737b8b1672f6bbadf27a6112fe95efc129dab9a13a1db921926519035223';

DEF_TS=0.0001;
DEF_PICKUP_TARGET=-0.005;
DEF_ESS2_AUTH=0.01;

if nargin<1 || isempty(modelRoot)
    modelRoot=['D:\Users\linjj\OPAL-RT\RT-LABv2024.1_Workspace\' ...
        'yanshou_V7\models\K26_K50_CLEAN_P1'];
end
modelRoot=canonicalPath(char(modelRoot));
modelFile=fullfile(modelRoot,[MODEL '.slx']);
if ~isfile(modelFile)
    error('S14V2R1:ModelMissing','当前正式模型不存在：%s',modelFile);
end

stamp=datestr(now,'yyyymmdd_HHMMSS_FFF');
workDir=fullfile(modelRoot,['PATCH_S14_V2_ESS2_PICKUP_HANDOVER_R1_' stamp]);
mkdir(workDir);
logFile=fullfile(workDir,'PATCH_LOG.txt');
fid=fopen(logFile,'w','n','UTF-8');
if fid<0,error('S14V2R1:Log','无法创建日志：%s',logFile);end
fidCleanup=onCleanup(@()safeClose(fid)); %#ok<NASGU>

result=struct();
result.version=VERSION;
result.modelFile=modelFile;
result.workDir=workDir;
result.sourceSha256=sha256File(modelFile);
result.status='STARTED';

fprintf(fid,'S14 V2 + ESS2固定小功率 + 平滑接管正式Patch R1\n');
fprintf(fid,'Model: %s\n',modelFile);
fprintf(fid,'Source raw SHA256（仅来源记录）: %s\n',result.sourceSha256);
fprintf(fid,'开始时间: %s\n\n',datestr(now,31));

% 同名模型如果已加载，只接受当前正式文件且Dirty=off。
if bdIsLoaded(MODEL)
    loadedFile=canonicalPath(get_param(MODEL,'FileName'));
    if ~strcmpi(loadedFile,modelFile)
        error('S14V2R1:WrongLoaded','同名模型从其他路径加载：%s',loadedFile);
    end
    if ~strcmp(get_param(MODEL,'Dirty'),'off')
        error('S14V2R1:Dirty','正式模型Dirty=on，请先人工处理未保存修改。');
    end
    close_system(MODEL,0);
end

% =========================================================================
% 1. 只读获取当前语义并封死pre版本
% =========================================================================
loadSystemExactFile(modelFile);
preCleanup=onCleanup(@()closeIfLoaded(MODEL)); %#ok<NASGU>
baseline=preflightCurrentModel(MODEL, ...
    EXPECTED_STRATEGY_PRE_SHA,EXPECTED_GATE_PRE_SHA,EXPECTED_COORD_PRE_SHA, ...
    EXPECTED_EXEC_PRE_SHA,EXPECTED_ADAPTER_SHA);
close_system(MODEL,0);

% Candidate（候选）源码由本脚本固定，不能运行时“猜当前文本怎么改”。
strategyCandidate=candidateStrategySource();
gateCandidate=candidateGateSource();
coordCandidate=candidateCoordinatorSource();
execCandidate=candidateExecutorSource();

staticSourceQA(strategyCandidate,'Advanced Strategy（15策略核心）');
staticSourceQA(gateCandidate,'Black Start Pref Gate（黑启动有功参考门）');
staticSourceQA(coordCandidate,'Island Coordinator（正常孤岛协调器核心）');
staticSourceQA(execCandidate,'ESS2 Restore Executor（恢复执行器）');
selftestCollectionNormalization();
selftestGeometryHelpers();

result.strategyCandidateSha256=hashText(strategyCandidate);
result.gateCandidateSha256=hashText(gateCandidate);
result.coordinatorCandidateSha256=hashText(coordCandidate);
result.executorCandidateSha256=hashText(execCandidate);

fprintf(fid,'[PASS] 当前语义preflight（预检查）与候选源码静态QA\n');

% =========================================================================
% 2. Production-equivalent ordinary-Simulink Harness（生产等价隔离测试）
% =========================================================================
runStrategyHarness(strategyCandidate);
runGateHarness(gateCandidate);
runCoordinatorHarness(coordCandidate);
runExecutorHarness(execCandidate);
runOwnershipBlendHarness();
fprintf(fid,'[PASS] 5组生产等价Harness：Strategy/Gate/Coordinator/Executor/OwnershipBlend\n');

% =========================================================================
% 3. Byte-identical scratch（字节一致临时副本）
% =========================================================================
scratchDir=fullfile(workDir,'SCRATCH');
mkdir(scratchDir);
scratchFile=fullfile(scratchDir,[MODEL '.slx']);
copyfile(modelFile,scratchFile,'f');
if ~strcmpi(sha256File(scratchFile),sha256File(modelFile))
    error('S14V2R1:ScratchCopy','Scratch不是字节一致复制。');
end

loadSystemExactFile(scratchFile);
scratchCleanup=onCleanup(@()closeIfLoaded(MODEL)); %#ok<NASGU>
scratchBase=preflightCurrentModel(MODEL, ...
    EXPECTED_STRATEGY_PRE_SHA,EXPECTED_GATE_PRE_SHA,EXPECTED_COORD_PRE_SHA, ...
    EXPECTED_EXEC_PRE_SHA,EXPECTED_ADAPTER_SHA);
assertEndpointMatricesEqual(baseline.g29First46,scratchBase.g29First46,'scratch pre G29前46');
applyPatchToLoadedModel(MODEL,strategyCandidate,gateCandidate,coordCandidate,execCandidate,DEF_TS,DEF_PICKUP_TARGET,DEF_ESS2_AUTH);
postassertPatchedModel(MODEL,strategyCandidate,gateCandidate,coordCandidate,execCandidate, ...
    EXPECTED_ADAPTER_SHA,scratchBase);

save_system(MODEL); % scratch恰好一次
scratchSavedSha=sha256File(scratchFile);
close_system(MODEL,0);
loadSystemExactFile(scratchFile);
postassertPatchedModel(MODEL,strategyCandidate,gateCandidate,coordCandidate,execCandidate, ...
    EXPECTED_ADAPTER_SHA,scratchBase);
if ~strcmp(get_param(MODEL,'Dirty'),'off')
    error('S14V2R1:ScratchDirty','Scratch重载后Dirty不为off。');
end
close_system(MODEL,0);
fprintf(fid,'[PASS] Scratch apply/postassert/save-once/reload/persistence\n');
fprintf(fid,'Scratch patched SHA256: %s\n',scratchSavedSha);

% =========================================================================
% 4. Formal whole-file backup + re-preflight + save exactly once
% =========================================================================
backupFile=fullfile(workDir,[MODEL '_PRE_S14_V2_ESS2_PICKUP_HANDOVER_R1_BACKUP.slx']);
copyfile(modelFile,backupFile,'f');
backupSha=sha256File(backupFile);
if ~strcmpi(backupSha,sha256File(modelFile))
    error('S14V2R1:Backup','正式整体备份不是字节一致复制。');
end
result.backupFile=backupFile;
result.backupSha256=backupSha;

formalSaved=false;
try
    loadSystemExactFile(modelFile);
    formalCleanup=onCleanup(@()closeIfLoaded(MODEL)); %#ok<NASGU>
    formalBase=preflightCurrentModel(MODEL, ...
        EXPECTED_STRATEGY_PRE_SHA,EXPECTED_GATE_PRE_SHA,EXPECTED_COORD_PRE_SHA, ...
        EXPECTED_EXEC_PRE_SHA,EXPECTED_ADAPTER_SHA);
    assertEndpointMatricesEqual(baseline.g29First46,formalBase.g29First46,'formal re-preflight G29前46');
    fprintf(fid,'[PASS] Formal re-preflight\n');

    applyPatchToLoadedModel(MODEL,strategyCandidate,gateCandidate,coordCandidate,execCandidate,DEF_TS,DEF_PICKUP_TARGET,DEF_ESS2_AUTH);
    postassertPatchedModel(MODEL,strategyCandidate,gateCandidate,coordCandidate,execCandidate, ...
        EXPECTED_ADAPTER_SHA,formalBase);

    save_system(MODEL); % 正式模型恰好一次
    formalSaved=true;
    result.patchedSha256=sha256File(modelFile);
    fprintf(fid,'[PASS] Formal save exactly once\n');

    close_system(MODEL,0);
    loadSystemExactFile(modelFile);
    postassertPatchedModel(MODEL,strategyCandidate,gateCandidate,coordCandidate,execCandidate, ...
        EXPECTED_ADAPTER_SHA,formalBase);
    if ~strcmp(get_param(MODEL,'Dirty'),'off')
        error('S14V2R1:FormalDirty','正式模型重载后Dirty不为off。');
    end
    close_system(MODEL,0);

    result.status='S14_V2_ESS2_PICKUP_HANDOVER_R1_SAVED_AND_PERSISTENCE_VERIFIED';
    fprintf(fid,'[PASS] Formal reload + persistence postassert\n');
catch ME
    try closeIfLoaded(MODEL);catch,end
    if formalSaved
        copyfile(backupFile,modelFile,'f');
        restoredSha=sha256File(modelFile);
        if ~strcmpi(restoredSha,backupSha)
            error('S14V2R1:RollbackFailed', ...
                '正式保存后发生错误，whole-file backup回滚SHA不一致。原错误：%s',ME.message);
        end
        fprintf(fid,'[ROLLBACK] 已用whole-file backup字节级恢复正式模型。\n');
    else
        fprintf(fid,'[NO ROLLBACK NEEDED] 错误发生在正式save_system之前，磁盘正式模型未被本Patch保存。\n');
    end
    rethrow(ME);
end

result.finishedAt=datestr(now,31);
writeText(fullfile(workDir,'RESULT.json'),jsonencode(result,'PrettyPrint',true));
fprintf(fid,'\n最终状态：%s\n',result.status);
fprintf(fid,'下一步：独立Verifier -> RT-LAB Rebuild All；不要先运行Python动态Runner。\n');

fprintf('\nS14 V2 + ESS2固定小功率/平滑接管 Patch R1 完成。\n');
fprintf('Status: %s\n',result.status);
fprintf('WorkDir: %s\n',workDir);
fprintf('下一步：VERIFY_K26_K50_S14_V2_ESS2_PICKUP_HANDOVER_R1\n');
end


